create or replace function public.reject_sale_when_business_closed()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_business_id bigint;
    v_stall_id public.business.stall_id%type;
    v_stall_number text;
    v_is_open boolean;
begin
    v_business_id := new.business_id;

    if v_business_id is null then
        select b.business_id
        into v_business_id
        from public.business b
        where (new.stall_id is not null and b.stall_id::text = new.stall_id::text)
           or (new.stall_number is not null and coalesce(b.stall_number, b.stall_no) = new.stall_number)
        order by b.business_id desc
        limit 1;
    end if;

    if v_business_id is null then
        raise exception 'SALE_BUSINESS_REQUIRED: The sale could not be matched to a business.' using errcode = '23514';
    end if;

    select b.stall_id, coalesce(b.stall_number, b.stall_no)
    into v_stall_id, v_stall_number
    from public.business b
    where b.business_id = v_business_id;

    if not found then
        raise exception 'SALE_BUSINESS_REQUIRED: The selected business does not exist.' using errcode = '23503';
    end if;

    if new.stall_id is not null and v_stall_id is not null and new.stall_id <> v_stall_id then
        raise exception 'SALE_STALL_MISMATCH: The sale stall does not belong to the selected business.' using errcode = '23514';
    end if;

    if new.stall_number is not null and v_stall_number is not null and new.stall_number <> v_stall_number then
        raise exception 'SALE_STALL_MISMATCH: The sale stall number does not belong to the selected business.' using errcode = '23514';
    end if;

    select s.is_open
    into v_is_open
    from public.business_operating_status s
    where s.business_id = v_business_id
    for share;

    if not found or not coalesce(v_is_open, false) then
        raise exception 'STALL_CLOSED: Open the stall before starting a sale.' using errcode = 'P0001';
    end if;

    new.business_id := v_business_id;
    new.stall_id := coalesce(v_stall_id, new.stall_id);
    new.stall_number := coalesce(v_stall_number, new.stall_number);
    return new;
end;
$$;

drop trigger if exists reject_sale_when_business_closed_before_insert on public.sales_transaction;
create trigger reject_sale_when_business_closed_before_insert
before insert on public.sales_transaction
for each row execute function public.reject_sale_when_business_closed();

create or replace function public.record_open_stall_sale(p_business_id bigint, p_rows jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_account_id bigint;
    v_stall_id public.business.stall_id%type;
    v_stall_number text;
    v_is_open boolean;
begin
    if auth.uid() is null or not public.can_manage_business_operating_status(p_business_id) then
        raise exception 'SALE_FORBIDDEN: Only the owner or approved personnel can record sales.' using errcode = '42501';
    end if;

    if p_rows is null or jsonb_typeof(p_rows) <> 'array' or jsonb_array_length(p_rows) = 0 then
        raise exception 'SALE_ROWS_REQUIRED: At least one sale row is required.' using errcode = '22023';
    end if;

    v_account_id := public.current_pos_account_id();

    select b.stall_id, coalesce(b.stall_number, b.stall_no)
    into v_stall_id, v_stall_number
    from public.business b
    where b.business_id = p_business_id;

    if not found then
        raise exception 'SALE_BUSINESS_REQUIRED: The selected business does not exist.' using errcode = '23503';
    end if;

    select s.is_open
    into v_is_open
    from public.business_operating_status s
    where s.business_id = p_business_id
    for share;

    if not found or not coalesce(v_is_open, false) then
        raise exception 'STALL_CLOSED: Open the stall before starting a sale.' using errcode = 'P0001';
    end if;

    insert into public.sales_transaction (
        business_id, stall_id, stall_number, account_id, username, category, product,
        product_listing_id, catalog_product_id, quantity_sold_kg, sold_quantity,
        sold_unit, unit_price_php, transaction_date, sync_date
    )
    select
        p_business_id,
        v_stall_id,
        v_stall_number,
        v_account_id,
        coalesce(r.username, ''),
        r.category,
        r.product,
        r.product_listing_id,
        r.catalog_product_id,
        r.quantity_sold_kg,
        coalesce(r.sold_quantity, r.quantity_sold_kg),
        r.sold_unit,
        r.unit_price_php,
        coalesce(r.transaction_date, now()),
        coalesce(r.sync_date, now())
    from jsonb_to_recordset(p_rows) as r(
        username text,
        category text,
        product text,
        product_listing_id text,
        catalog_product_id uuid,
        quantity_sold_kg numeric,
        sold_quantity numeric,
        sold_unit text,
        unit_price_php numeric,
        transaction_date timestamptz,
        sync_date timestamptz
    );
end;
$$;

