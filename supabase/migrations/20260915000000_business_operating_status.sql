create or replace function public.get_business_operating_status(p_business_id bigint)
returns table (
    business_id bigint,
    stall_number text,
    is_open boolean,
    updated_at timestamptz,
    updated_by_account_id bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
    if auth.uid() is null or not public.can_read_business_operating_status(p_business_id) then
        raise exception 'OPERATING_STATUS_FORBIDDEN: You are not authorized to view this business.' using errcode = '42501';
    end if;

    return query
    select s.business_id, s.stall_number, s.is_open, s.updated_at, s.updated_by_account_id
    from public.business_operating_status s
    where s.business_id = p_business_id;
end;
$$;

create or replace function public.set_business_operating_status(p_business_id bigint, p_is_open boolean)
returns table (
    business_id bigint,
    stall_number text,
    is_open boolean,
    updated_at timestamptz,
    updated_by_account_id bigint
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_status public.business_operating_status%rowtype;
    v_account_id bigint;
begin
    if auth.uid() is null or not public.can_manage_business_operating_status(p_business_id) then
        raise exception 'OPERATING_STATUS_FORBIDDEN: Only the owner or approved personnel can change this status.' using errcode = '42501';
    end if;

    v_account_id := public.current_pos_account_id();

    insert into public.business_operating_status (business_id, stall_number, is_open)
    select b.business_id, coalesce(b.stall_number, b.stall_no), false
    from public.business b
    where b.business_id = p_business_id
    on conflict (business_id) do nothing;

    select * into v_status
    from public.business_operating_status s
    where s.business_id = p_business_id
    for update;

    if not found then
        raise exception 'OPERATING_STATUS_NOT_FOUND: Business status was not found.' using errcode = 'P0002';
    end if;

    if v_status.is_open is distinct from p_is_open then
        update public.business_operating_status s
        set is_open = p_is_open,
            updated_at = now(),
            updated_by_account_id = v_account_id
        where s.business_id = p_business_id
        returning * into v_status;

    end if;

    return query
    select v_status.business_id, v_status.stall_number, v_status.is_open,
           v_status.updated_at, v_status.updated_by_account_id;
end;
$$;

