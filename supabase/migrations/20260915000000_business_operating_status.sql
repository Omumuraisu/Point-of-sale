create table if not exists public.business_operating_status (
    business_id bigint primary key references public.business(business_id) on delete cascade,
    stall_number text not null,
    is_open boolean not null default false,
    updated_at timestamptz not null default now(),
    updated_by_account_id bigint references public.accounts(account_id) on delete set null
);

create table if not exists public.business_operating_status_history (
    history_id bigint generated by default as identity primary key,
    business_id bigint not null references public.business(business_id) on delete cascade,
    stall_number text not null,
    previous_is_open boolean not null,
    is_open boolean not null,
    changed_at timestamptz not null default now(),
    changed_by_account_id bigint references public.accounts(account_id) on delete set null
);

create index if not exists business_operating_status_history_business_changed_idx
    on public.business_operating_status_history (business_id, changed_at desc);

insert into public.business_operating_status (business_id, stall_number, is_open)
select b.business_id, coalesce(b.stall_number, b.stall_no), true
from public.business b
on conflict (business_id) do nothing;

create or replace function public.initialize_business_operating_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.business_operating_status (business_id, stall_number, is_open)
    values (new.business_id, coalesce(new.stall_number, new.stall_no), false)
    on conflict (business_id) do update
    set stall_number = excluded.stall_number
    where public.business_operating_status.stall_number is distinct from excluded.stall_number;
    return new;
end;
$$;

drop trigger if exists initialize_business_operating_status_after_insert on public.business;
create trigger initialize_business_operating_status_after_insert
after insert on public.business
for each row execute function public.initialize_business_operating_status();

drop trigger if exists synchronize_business_operating_stall_after_update on public.business;
create trigger synchronize_business_operating_stall_after_update
after update of stall_number, stall_no on public.business
for each row execute function public.initialize_business_operating_status();

create or replace function public.audit_business_operating_status_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    if old.is_open is distinct from new.is_open then
        insert into public.business_operating_status_history (
            business_id, stall_number, previous_is_open, is_open, changed_by_account_id
        ) values (
            new.business_id, new.stall_number, old.is_open, new.is_open, new.updated_by_account_id
        );
    end if;
    return new;
end;
$$;

drop trigger if exists audit_business_operating_status_after_update on public.business_operating_status;
create trigger audit_business_operating_status_after_update
after update on public.business_operating_status
for each row execute function public.audit_business_operating_status_change();

create or replace function public.current_pos_account_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
    select a.account_id
    from public.accounts a
    where a.auth_user_id = auth.uid()
      and lower(coalesce(a.status::text, '')) = 'active'
      and coalesce(a.is_verified, false) = true
    limit 1
$$;

create or replace function public.can_read_business_operating_status(p_business_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.accounts a
        left join public.business_owner bo on bo.account_id = a.account_id
        left join public.vendor v on v.account_id = a.account_id
        join public.business b on b.business_id = p_business_id
        where a.auth_user_id = auth.uid()
          and lower(coalesce(a.status::text, '')) = 'active'
          and coalesce(a.is_verified, false) = true
          and (
              (bo.business_owner_id = b.business_owner_id and bo.archived_at is null)
              or (
                  v.business_owner_id = b.business_owner_id
                  and coalesce(v.is_approved, false) = true
              )
              or lower(a.user_type::text) = 'developer'
          )
    )
$$;

create or replace function public.can_manage_business_operating_status(p_business_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.accounts a
        left join public.business_owner bo on bo.account_id = a.account_id
        left join public.vendor v on v.account_id = a.account_id
        join public.business b on b.business_id = p_business_id
        where a.auth_user_id = auth.uid()
          and lower(coalesce(a.status::text, '')) = 'active'
          and coalesce(a.is_verified, false) = true
          and (
              (bo.business_owner_id = b.business_owner_id and bo.archived_at is null)
              or (
                  v.business_owner_id = b.business_owner_id
                  and coalesce(v.is_approved, false) = true
              )
          )
    )
$$;

alter table public.business_operating_status enable row level security;
alter table public.business_operating_status_history enable row level security;

drop policy if exists "Authorized accounts can read operating status" on public.business_operating_status;
